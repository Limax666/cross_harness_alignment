#!/usr/bin/env python3
"""Run one held-out ActBench rollout per pair on Hermes and Claude Code.

Run once for each model role. Each role uses one persistent local model server;
the two harnesses are evaluated in small, resumable batches to limit I/O.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
import urllib.request
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
EXP = ROOT / "experiments/cross_harness_sft"
OUT = EXP / "outputs/actbench/dedup_qwen35_2b_v7"
BENCH = EXP / "vendor/actbench"
PYTHON = Path("/data/home/liumingxiao/miniforge3/envs/cross-harness-sft/bin/python")
HERMES = Path("/data/home/liumingxiao/.hermes/hermes-agent/venv/bin/hermes")
CLAUDE = Path("/data/home/liumingxiao/.npm-global/bin/claude")
REVISION = "31bd732e9c083ddeb19bf152048386d38e511c90"
PORTS = {"base": (9160, 9161), "sft": (9170, 9171)}
MCP_PORTS = {("base", "hermes"): 8774, ("base", "claudecode"): 8775,
             ("sft", "hermes"): 8776, ("sft", "claudecode"): 8777}


def write_json(path: Path, obj: object) -> None:
    temp = path.with_suffix(path.suffix + ".tmp")
    temp.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    temp.replace(path)


def completed_batch(directory: Path, expected: list[str]) -> bool:
    matches = list(directory.glob("[0-9][0-9][0-9][0-9]_*.json"))
    if not matches:
        return False
    for path in matches:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            if data.get("workflow") != "trajectory_collection":
                continue
            if data.get("runs_per_task") != 1:
                continue
            tasks = data.get("tasks") or []
            if sorted(task.get("task_id") for task in tasks) == sorted(expected):
                return True
        except (OSError, ValueError, TypeError):
            continue
    return False


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--role", choices=PORTS, required=True)
    parser.add_argument("--batch-size", type=int, default=8)
    args = parser.parse_args()
    if args.batch_size < 1:
        parser.error("--batch-size must be positive")
    manifest = json.loads((OUT / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("benchmark_revision") != REVISION:
        raise SystemExit("ActBench source revision does not match dedup manifest")
    commit = subprocess.check_output(["git", "-C", str(BENCH), "rev-parse", "HEAD"], text=True).strip()
    if commit != REVISION:
        raise SystemExit(f"ActBench source must be pinned to {REVISION}; got {commit}")
    ids = [str(pair["task_id"]) for pair in manifest["task_pairs"]]
    if len(ids) != 264 or len(set(ids)) != 264:
        raise SystemExit("Expected 264 unique held-out task pairs")
    server_port, gateway_port = PORTS[args.role]
    for port in (server_port, gateway_port):
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/health", timeout=15) as response:
            if response.status != 200:
                raise SystemExit(f"Local model endpoint on port {port} is unhealthy")
    model = f"qwen35-2b-{args.role}-actbench"
    state_dir = OUT / "one_round_t480_r1" / args.role
    state_dir.mkdir(parents=True, exist_ok=True)
    progress_path = state_dir / "progress.json"
    write_json(state_dir / "run_manifest.json", {
        "benchmark_revision": REVISION, "dedup_manifest": str(OUT / "manifest.json"),
        "role": args.role, "model": model, "harnesses": ["hermes", "claudecode"],
        "task_pairs": len(ids), "rollouts_per_pair_per_harness": 1,
        "expected_attack_trajectories": len(ids) * 2,
        "benign_baseline": "generated by official ActBench runner and cached per scene",
        "batch_size": args.batch_size, "judge_model": "judge/openai/gpt-5.4-nano",
        "timeout_multiplier": 4.0,
        "execution_retries": 1,
        "retry_statuses": ["timeout", "error"],
        "hermes_max_turns": 40,
        "superseded_previous_run": str(OUT / "one_round" / args.role),
    })
    for harness in ("hermes", "claudecode"):
        harness_dir = state_dir / harness
        harness_dir.mkdir(parents=True, exist_ok=True)
        env = os.environ.copy()
        env.update({
            "ACTBENCH_RUN_ROOT": str(harness_dir / "workspaces"),
            "ACTBENCH_BASELINE_CACHE_DIR": str(harness_dir / "baseline_cache"),
            "ACTBENCH_MCP_PORT": str(MCP_PORTS[(args.role, harness)]),
            "ACTBENCH_LLM_BACKENDS_CONFIG": str(OUT / "judge_provider.yaml"),
            "HF_HUB_OFFLINE": "1",
        })
        if harness == "hermes":
            env.update({"ACTBENCH_HERMES_BIN": str(HERMES),
                        "ACTBENCH_HERMES_PROVIDER": "custom",
                        "CUSTOM_BASE_URL": f"http://127.0.0.1:{server_port}/v1",
                        "OPENAI_API_KEY": "local"})
        else:
            env.update({"ACTBENCH_CLAUDECODE_BIN": str(CLAUDE),
                        "ACTBENCH_CLAUDECODE_MODEL": model,
                        "ANTHROPIC_BASE_URL": f"http://127.0.0.1:{gateway_port}",
                        "ANTHROPIC_AUTH_TOKEN": "local",
                        "ANTHROPIC_API_KEY": "local",
                        "CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC": "1"})
        for offset in range(0, len(ids), args.batch_size):
            batch_ids = ids[offset:offset + args.batch_size]
            batch_dir = harness_dir / f"batch_{offset // args.batch_size + 1:03d}"
            batch_dir.mkdir(parents=True, exist_ok=True)
            if completed_batch(batch_dir, batch_ids):
                print(f"[{args.role}/{harness}] skipped completed {batch_dir.name}", flush=True)
                continue
            command = [str(PYTHON), "-u", str(BENCH / "scripts/actbench.py"),
                       "--backend", harness, "--model", model,
                       "--suite", ",".join(batch_ids), "--runs", "1", "--run-workers", "1",
                       "--timeout-multiplier", "4", "--execution-retries", "1",
                       "--retry-status", "timeout,error",
                       "--judge-model", "judge/openai/gpt-5.4-nano",
                       "--output-dir", str(batch_dir), "--no-fail-fast"]
            print(f"[{args.role}/{harness}] {batch_dir.name}: {len(batch_ids)} pairs", flush=True)
            log_path = batch_dir / "runner.log"
            with log_path.open("a", encoding="utf-8") as log:
                log.write(f"\n=== started {time.strftime('%Y-%m-%d %H:%M:%S')} ===\n")
                log.flush()
                proc = subprocess.run(command, cwd=batch_dir, env=env, stdout=log, stderr=subprocess.STDOUT)
            if proc.returncode or not completed_batch(batch_dir, batch_ids):
                raise SystemExit(f"Batch failed or incomplete: {batch_dir}; see {log_path}")
            write_json(progress_path, {"role": args.role, "harness": harness,
                                       "last_completed_batch": batch_dir.name,
                                       "last_task_id": batch_ids[-1], "completed_at": time.time()})
            # Avoid simultaneous workspace churn from both model roles.
            time.sleep(2)
    write_json(progress_path, {"role": args.role, "status": "collection_complete",
                               "harnesses": ["hermes", "claudecode"], "completed_at": time.time()})
    print(f"[{args.role}] one-round collection complete", flush=True)


if __name__ == "__main__":
    main()
